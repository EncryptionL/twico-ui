#!/usr/bin/env node
/**
 * Concatenate the design-token layers + base reset into the shippable stylesheets:
 *
 *   styles/twico-ui.css      the AUTHORING copy  (twico-ui/styles.css)      — comments kept
 *   styles/twico-ui.min.css  the LOADING copy    (twico-ui/styles.min.css)  — minified
 *
 * This file used to be maintained by hand, which let it drift from the real
 * `tokens/*.css` + `base.css` sources. Now it is generated:
 *   npm run build:css              regenerate both
 *   npm run build:css -- --check   fail (exit 1) if either is stale (used in CI)
 *
 * The only transform vs. the sources is the @font-face url(): the dev sources
 * point at `../assets/fonts/`; in the published package the fonts ship beside
 * these stylesheets in `./fonts/`.
 *
 * TWO COPIES, NOT ONE (#539). #534 stripped the comments from the single generated stylesheet and
 * measured a real win - 28,541 bytes to 15,954, 7.41 kB to 3.28 kB brotli, on a file every consumer
 * imports at their app root. What it also did was strip the AUTHORING surface: `twico-ui.css` is the
 * file someone opens to re-skin the library, and 144 comments went with it, including 16 carrying
 * the contrast ratio behind a colour ("white ink on it is 4.47:1, under 4.5") and the
 * "remap these to re-skin the whole library" signpost itself. A re-skinner then has no in-file
 * signal that a value was picked to clear WCAG 1.4.3.
 * So: the documented authoring name keeps its comments, and the saving moves to a second file the
 * consumer can opt into. Both are generated from the same sources by the same run, and --check
 * guards both, so they cannot disagree.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { brotliCompressSync } from "node:zlib";
import { minifyCss } from "./css-minify.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "styles", "twico-ui.css");
const OUT_MIN = join(ROOT, "styles", "twico-ui.min.css");
const LF = String.fromCharCode(10);
// The brotli budget for the LOADING copy, in bytes. #534 noted that the stylesheet was not covered
// by any size budget, which is how 12.6 kB of comments got onto every consumer's page in the first
// place. It lives here rather than in size-limit because that preset bundles every `path` it is
// given through rolldown, and a .css entry is not a JS module - so the guard runs wherever the file
// is generated, on `build:css` as well as `build:css:check`.
const MIN_BROTLI_BUDGET = 3300;
const CR = String.fromCharCode(13);

// Order matters: fonts first (so @font-face is defined), then tokens, then base.
const LAYERS = [
  "tokens/fonts.css",
  "tokens/colors.css",
  "tokens/typography.css",
  "tokens/spacing.css",
  "tokens/radius.css",
  "tokens/motion.css",
  "base.css",
];

const HEADER = `/* ============================================================
   twico-ui — bundled stylesheet (design tokens + base reset + webfonts)
   Import ONCE at your app root:   import "twico-ui/styles.css";
   Dark mode:  add class="dark" (or data-theme="dark") to <html>.
   Fonts ship beside this file in ./fonts/ (self-hosted, OFL).

   The comments below are the point of this copy: they record WHY a token
   holds the value it does — contrast ratios, which aliases to remap to
   re-skin, which boundaries are a control's only affordance. Re-skinning
   starts here. For loading, import "twico-ui/styles.min.css" instead:
   same rules, same cascade, no comments and no whitespace.

   GENERATED by scripts/build-css.mjs from tokens/*.css + base.css —
   do not edit by hand; run \`npm run build:css\` after editing a source.
   ============================================================ */
`;

const HEADER_MIN = `/* twico-ui — bundled stylesheet, minified. Authoring copy with comments: twico-ui/styles.css
   GENERATED by scripts/build-css.mjs — do not edit by hand. */
`;

async function generate() {
  const parts = [HEADER];
  for (const rel of LAYERS) {
    // Normalised to LF here, not at compare time: with core.autocrlf=true a working copy is CRLF
    // and CI's checkout is LF, and a generator that passes line endings through produces a
    // different file on each (#534's CI-only build:css:check failure).
    let css = (await readFile(join(ROOT, rel), "utf8")).split(CR).join("");
    if (rel === "tokens/fonts.css") {
      // Dev sources reference ../assets/fonts/; the package ships fonts in ./fonts/.
      css = css.replace(/\.\.\/assets\/fonts\//g, "./fonts/");
    }
    parts.push(`${LF}/* ===== ${rel} ===== */${LF}${css.trimEnd()}${LF}`);
  }
  return parts.join("");
}

const next = await generate();
// Minified from the SAME string the authoring copy is written from, so the two can never describe
// different stylesheets. The header is re-added after minifying - it is the one comment that has to
// survive, because it is what tells a reader where the file came from.
const nextMin = HEADER_MIN + minifyCss(next);
const minBrotli = brotliCompressSync(Buffer.from(nextMin, "utf8")).length;
if (minBrotli > MIN_BROTLI_BUDGET) {
  console.error(
    "✗ styles/twico-ui.min.css is " + minBrotli + " B brotli, over the " + MIN_BROTLI_BUDGET +
    " B budget. Either the token layers grew for a reason - raise MIN_BROTLI_BUDGET in " +
    "scripts/build-css.mjs and say why in docs/bundle-size.md - or something is shipping that " +
    "should not be."
  );
  process.exit(1);
}

const check = process.argv.includes("--check");
const norm = (s) => s.replace(/\r\n/g, "\n");

async function read(p) {
  try { return await readFile(p, "utf8"); } catch { return ""; }
}

if (check) {
  const stale = [];
  if (norm(await read(OUT)) !== norm(next)) stale.push("styles/twico-ui.css");
  if (norm(await read(OUT_MIN)) !== norm(nextMin)) stale.push("styles/twico-ui.min.css");
  if (stale.length) {
    console.error(`✗ ${stale.join(" and ")} ${stale.length > 1 ? "are" : "is"} stale. Run \`npm run build:css\` and commit the result.`);
    process.exit(1);
  }
  console.log(`✓ styles/twico-ui.css and styles/twico-ui.min.css are up to date (${minBrotli} B brotli of ${MIN_BROTLI_BUDGET} B).`);
} else {
  await writeFile(OUT, next, "utf8");
  await writeFile(OUT_MIN, nextMin, "utf8");
  const pct = Math.round((1 - nextMin.length / next.length) * 100);
  console.log(`✓ Wrote styles/twico-ui.css (${next.length} B) + styles/twico-ui.min.css (${nextMin.length} B, -${pct}%, ${minBrotli} B brotli of ${MIN_BROTLI_BUDGET} B) from ${LAYERS.length} sources.`);
}
